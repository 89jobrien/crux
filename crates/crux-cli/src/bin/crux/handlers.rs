#[derive(Debug, Clone, Copy, clap::ValueEnum)]
pub enum HandlerFormat {
    Markdown,
    Json,
}

pub fn cmd_handlers(format: HandlerFormat, plugins: Option<&str>, output: Option<&str>) {
    let runtime = tokio::runtime::Runtime::new().expect("Tokio runtime");
    let registry = runtime.block_on(super::registry::build_base_registry(plugins));
    let metadata = registry.handler_metadata();

    let content = match format {
        HandlerFormat::Json => serde_json::to_string_pretty(&metadata).expect("JSON serialization"),
        HandlerFormat::Markdown => {
            let mut buf = String::new();
            buf.push_str("# Handler catalog\n\n");
            buf.push_str("<!-- generated by `crux handlers` — do not edit by hand -->\n\n");
            for handler in &metadata {
                buf.push_str(&format!("## `{}`\n\n", handler.name));
                if !handler.description.is_empty() {
                    buf.push_str(&format!("{}\n\n", handler.description));
                }
                buf.push_str(&format!("- **Risk:** `{:?}`\n", handler.risk));
                buf.push_str(&format!(
                    "- **Deterministic:** `{}`\n",
                    handler.deterministic
                ));
                buf.push_str(&format!(
                    "- **Capabilities:** `{:?}`\n",
                    handler.capabilities
                ));
                buf.push_str(&format!(
                    "- **Side effects:** `{:?}`\n\n",
                    handler.side_effects
                ));
                buf.push_str("### Arguments\n\n");
                if handler.args.args.is_empty() {
                    buf.push_str("No declared arguments.\n\n");
                } else {
                    buf.push_str("| Name | Required | Schema | Description |\n");
                    buf.push_str("| --- | --- | --- | --- |\n");
                    for argument in &handler.args.args {
                        buf.push_str(&format!(
                            "| `{}` | {} | `{:?}` | {} |\n",
                            argument.name,
                            argument.required,
                            argument.schema,
                            argument.description.as_deref().unwrap_or("")
                        ));
                    }
                    buf.push('\n');
                }
                buf.push_str("### Output\n\n");
                buf.push_str(&format!("`{:?}`\n\n", handler.output_schema));
            }
            buf
        }
    };

    match output {
        Some(path) => {
            std::fs::write(path, &content).unwrap_or_else(|e| {
                eprintln!("error: cannot write to {path}: {e}");
                std::process::exit(1);
            });
        }
        None => print!("{content}"),
    }
}
