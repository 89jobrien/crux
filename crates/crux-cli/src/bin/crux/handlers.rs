#[derive(Debug, Clone, Copy, clap::ValueEnum)]
pub enum HandlerFormat {
    Markdown,
    Json,
}

pub fn cmd_handlers(format: HandlerFormat, plugins: Option<&str>, output: Option<&str>) {
    let runtime = tokio::runtime::Runtime::new().expect("Tokio runtime");
    let registry = runtime.block_on(super::registry::build_base_registry(plugins));
    let metadata = registry.handler_metadata();

    let content = match format {
        HandlerFormat::Json => serde_json::to_string_pretty(&metadata).expect("JSON serialization"),
        HandlerFormat::Markdown => {
            let mut buf = String::new();
            buf.push_str("# Handler catalog\n\n");
            buf.push_str("<!-- generated by `crux handlers` — do not edit by hand -->\n\n");
            for handler in &metadata {
                buf.push_str(&format!("## `{}`\n\n", handler.name));
                if !handler.description.is_empty() {
                    buf.push_str(&format!("{}\n\n", handler.description));
                }
                buf.push_str(&format!("- **Risk:** `{:?}`\n", handler.risk));
                buf.push_str(&format!(
                    "- **Deterministic:** `{}`\n",
                    handler.deterministic
                ));
                buf.push_str(&format!(
                    "- **Capabilities:** `{:?}`\n",
                    handler.capabilities
                ));
                buf.push_str(&format!(
                    "- **Side effects:** `{:?}`\n\n",
                    handler.side_effects
                ));
                buf.push_str("### Arguments\n\n");
                if handler.args.args.is_empty() {
                    buf.push_str("No declared arguments.\n\n");
                } else {
                    let rows: Vec<Vec<String>> = handler
                        .args
                        .args
                        .iter()
                        .map(|argument| {
                            vec![
                                format!("`{}`", argument.name),
                                argument.required.to_string(),
                                format!("`{:?}`", argument.schema),
                                argument.description.clone().unwrap_or_default(),
                            ]
                        })
                        .collect();
                    push_table(
                        &mut buf,
                        &["Name", "Required", "Schema", "Description"],
                        &rows,
                    );
                    buf.push('\n');
                }
                buf.push_str("### Output\n\n");
                buf.push_str(&format!("`{:?}`\n\n", handler.output_schema));
            }
            buf.truncate(buf.trim_end().len());
            buf.push('\n');
            buf
        }
    };

    match output {
        Some(path) => {
            std::fs::write(path, &content).unwrap_or_else(|e| {
                eprintln!("error: cannot write to {path}: {e}");
                std::process::exit(1);
            });
        }
        None => print!("{content}"),
    }
}

/// Writes a Markdown table with each column padded to its widest cell, which is
/// the layout the repository's markdown formatter leaves checked-in tables in.
fn push_table(buf: &mut String, headers: &[&str], rows: &[Vec<String>]) {
    let widths: Vec<usize> = headers
        .iter()
        .enumerate()
        .map(|(col, header)| {
            rows.iter()
                .map(|row| row[col].chars().count())
                .fold(header.chars().count(), usize::max)
        })
        .collect();

    let push_line = |buf: &mut String, cells: Vec<String>| {
        buf.push('|');
        for (cell, width) in cells.iter().zip(&widths) {
            buf.push_str(&format!(" {cell:<width$} |", width = *width));
        }
        buf.push('\n');
    };

    push_line(
        buf,
        headers.iter().map(|header| header.to_string()).collect(),
    );
    push_line(buf, widths.iter().map(|width| "-".repeat(*width)).collect());
    for row in rows {
        push_line(buf, row.clone());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The reference catalog checked into the repository.
    const CHECKED_IN: &str = include_str!("../../../../../docs/handler-catalog.md");

    #[test]
    fn checked_in_handler_catalog_matches_generated_output() {
        // A nonexistent plugins path keeps the catalog to built-in handlers,
        // so the result does not depend on the developer's ~/.crux/plugins.toml.
        let path =
            std::env::temp_dir().join(format!("crux-handler-catalog-{}.md", std::process::id()));
        cmd_handlers(
            HandlerFormat::Markdown,
            Some("/nonexistent/crux-test-plugins.toml"),
            path.to_str(),
        );
        let generated = std::fs::read_to_string(&path).expect("catalog was written");
        let _ = std::fs::remove_file(&path);

        assert!(
            generated == CHECKED_IN,
            "docs/handler-catalog.md is out of date; regenerate with \
             `crux handlers --output docs/handler-catalog.md`"
        );
    }
}
